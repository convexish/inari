//! Revision-five structured continuation records. Context tokens are ordered,
//! unpooled records; a header starts a record, whose ordinal is its local ID.
//! Field payloads use little-endian 16-bit limbs, exactly representable in f32.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u16)]
pub enum RecordKind {
    Reference = 1,
    Action,
    Execution,
    Effect,
    Karma,
    Slot,
    Pending,
    Record,
    Parameter,
    Block,
    Item,
    Operation,
    Batch,
    Exchange,
    Group,
    Schedule,
    Promotion,
    Reveal,
    Opaque,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u16)]
pub enum Field {
    Parent = 1,
    Role,
    Detail,
    Executor,
    Controller,
    Demander,
    SourceOwner,
    Life,
    Slot,
    Owner,
    Append,
    Choice,
    ScalarKind,
    Scalar,
    Ordinal,
    Origin,
    Stage,
    Cursor,
    Effect,
    Count,
    Limit,
    Performed,
    Replaced,
    Failed,
    Colors,
    Foreseen,
    Shared,
    Endorsed,
    Promoted,
    ActionKind,
    Verb,
    SourceZone,
    Destination,
    Back,
    Mode,
    Optional,
    Stopped,
    Constraint,
    Side,
    Committing,
    Frozen,
    Bound,
    Last,
    Chosen,
    Value,
    Suppressed,
    Requested,
    Known,
    Remaining,
    PublicOutcome,
}
/// Header code is HEADER + RecordKind; following fields belong to that record.
pub const HEADER: u32 = 256;
/// Field code is FIELD + 4 * Field + limb (0..4), least significant first.
pub const FIELD: u32 = 512;
